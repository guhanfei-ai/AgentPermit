package handler

// errorAIInstruction 只解释当前拒绝及后续处理，不包含密钥、主体身份或内部封禁规则。
// 新动作可在这里登记通用说明，或通过 writeJSONError 提供本次动作的专用说明。
func errorAIInstruction(code string) string {
	switch code {
	case "holiday_lockdown":
		return "管理员已启用封网。封网期间禁止 AI 进行自动化作业。请立即停止自动化调用，不要自动重试、轮询恢复状态、重新申请凭证或更换入口尝试绕过；向人类报告当前因管理员封网而受阻，等待封网解除并收到人类新的继续指令后再恢复。"
	case "person_banned":
		return "管理员已封禁当前账号的 AI 作业。请停止该账号的自动化调用，不要自动重试、轮询或换凭证、换入口绕过；向人类报告受阻原因，等待管理员解除封禁并收到人类新的继续指令。"
	case "credential_banned":
		return "管理员已封禁当前 AI 凭证。请停止使用该凭证进行自动化作业，不要自动重试、轮询或申请其他凭证绕过；向人类报告受阻原因，等待管理员处理并收到人类新的继续指令。"
	case "conditional_banned":
		return "本次作业命中了管理员设置的条件封禁。请停止相关自动化调用，不要自动重试、轮询或修改申报值、凭证、入口尝试绕过；向人类报告当前受阻，等待管理员处理并收到人类新的继续指令。"
	case "grant_denied":
		return "当前身份、目标服务或管理员管控状态不允许签发临时凭证。请停止本次自动化作业，不要自动重试、循环申请凭证或换入口尝试；向人类报告受阻并等待处理。"
	case "server_disabled":
		return "管理员已停用目标受管服务。请停止向该服务发起自动化调用，不要自动重试、轮询或改用其他入口绕过；向人类报告服务已停用，等待管理员处理。"
	case "parent_credential_invalid":
		return "当前临时凭证的原始凭证或所属账号已失效，可能已被撤销、轮换或停用。请停止使用现有凭证，不要自动重试或循环申请；向人类报告并等待确认有效的接入配置。"
	case "grant_revoked":
		return "当前临时凭证已被撤销。请停止本次自动化调用，不要自动重试或重新申请凭证绕过撤销；向人类报告并等待新的明确指令。"
	case "banned":
		return "当前账号或凭证已被限制在该频道发言。请停止向该频道自动发言，不要自动重试或换凭证绕过；向人类报告并等待频道管理员处理。"
	default:
		return ""
	}
}
